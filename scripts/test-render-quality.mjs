import assert from 'node:assert/strict';
import {createQualityController} from '../src/app/render-quality.ts';
const low=createQualityController({mobile:true,memory:4,cores:8});
assert.equal(low.get().targetFps,30);
assert.equal(low.get().resolution,1);
assert.equal(low.get().heroScale,1);
const fast=createQualityController({mobile:true,memory:8,cores:8});
assert.equal(fast.get().targetFps,60);
const unknown=createQualityController({mobile:true,cores:8});
assert.equal(unknown.get().tier,'balanced');
const desktop=createQualityController({mobile:false,memory:4,cores:8});
assert.equal(desktop.get().tier,'high','4GB hint alone must not identify every desktop as low-spec');
const clocks=new WeakMap();
const feed=(controller,dt,seconds=5,capped=false)=>{let t=clocks.get(controller)??100;const end=t+seconds*1000;for(;t<=end;t+=dt)controller.noteFrame(t,dt,capped);clocks.set(controller,t);};
feed(desktop,1000/60);assert.equal(desktop.get().tier,'high','healthy cadence retains quality');
let changes=0;desktop.subscribe(()=>changes++);
feed(desktop,40);assert.equal(desktop.get().tier,'balanced','sustained late frames lower quality');
feed(desktop,50);assert.equal(desktop.get().tier,'low');assert.equal(changes,2);
feed(desktop,1000/30);assert.equal(desktop.get().targetFps,30,'healthy low cadence remains stable');
const capped=createQualityController({mobile:false});feed(capped,1000/30,8,true);
assert.equal(capped.get().tier,'high','browser cap must not be mistaken for GPU overload');
const hitch=createQualityController({mobile:false});for(let t=100;t<6000;t+=16.67)hitch.noteFrame(t,t>3000&&t<3100?150:16.67);
assert.equal(hitch.get().tier,'high','a few isolated stalls do not lower quality');
const pinned=createQualityController({mobile:true,memory:4},'high');feed(pinned,80,8);
assert.equal(pinned.get().tier,'high','explicit choice overrides hints and governor');
const suspended=createQualityController({mobile:false});feed(suspended,40,2);suspended.noteFrame(10000,2000);feed(suspended,16.67,6);
assert.equal(suspended.get().tier,'high','suspension must clear the evidence window');
console.log('PASS quality selection, 30/60 targets, sustained downgrade, isolated hitches, suspension, cap and override');
