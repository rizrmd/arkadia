// The canonical effect generated by `nixie-fx effect create` for the 2D Pixi profile.
export function defaults(){
 if(template)return structuredClone(template);
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'nixie-template-'));
 try{
  fs.mkdirSync(path.join(dir,'effects'));fs.mkdirSync(path.join(dir,'assets/materials'),{recursive:true});
  fs.writeFileSync(path.join(dir,'vfx-editor.prj'),JSON.stringify({app:'vfx-editor',kind:'project',version:1,id:'template',name:'Template',settings:{effectDataPath:'effects',outputPath:'out/vfx',assetRootPath:'assets',materialsFolder:'materials',allowExternalOutput:false,lastEffectFile:'template.json'},createdAt:'2026-01-01T00:00:00.000Z',updatedAt:'2026-01-01T00:00:00.000Z'}));
  execFileSync(process.execPath,[CLI,'effect','create','--project',dir,'--name','Template','--profile','pixi-ui-2d'],{stdio:'pipe'});
  template=JSON.parse(fs.readFileSync(path.join(dir,'effects/template.json'),'utf8'));
 }finally{fs.rmSync(dir,{recursive:true,force:true});}
 return structuredClone(template);
}

const get=(o,p)=>p.split('.').reduce((v,k)=>v?.[k],o);
function set(o,p,v){const ks=p.split('.'),last=ks.pop();let t=o;for(const k of ks)t=t[k];if(!(last in t))throw Error(`Unknown NixieFX field ${p}`);t[last]=v;}

// Scalars: 3 → constant · [min,max] → random · {curve:[[t,v]…]} → over normalised time · {curve,curveB} → random between curves.
function scalar(base,spec){
 const e=structuredClone(base),pts=a=>a.map(([x,y])=>({x,y}));
 // Curves of constant/random scalars stay at the template value: unused at runtime, and the packer drops them.
 if(typeof spec==='number')Object.assign(e,{mode:'constant',value:spec,min:spec,max:spec});
 else if(Array.isArray(spec))Object.assign(e,{mode:'random',value:(spec[0]+spec[1])/2,min:spec[0],max:spec[1]});
 else if(spec&&spec.curve){const a=pts(spec.curve),b=spec.curveB?pts(spec.curveB):a;Object.assign(e,{mode:spec.curveB?'randomCurve':'curve',value:a[0].y,min:Math.min(...a.map(p=>p.y),...b.map(p=>p.y)),max:Math.max(...a.map(p=>p.y),...b.map(p=>p.y)),curve:a,curveB:b});}
 else throw Error('Bad scalar '+JSON.stringify(spec));
 const values=[e.value,e.min,e.max,...e.curve.map(p=>p.y),...e.curveB.map(p=>p.y)];
 e.editorMin=Math.min(e.editorMin,...values);e.editorMax=Math.max(e.editorMax,...values);
 return e;
}
export const rgb=hex=>{const h=hex.replace('#','');return [0,2,4].map(i=>+(parseInt(h.slice(i,i+2),16)/255).toFixed(4));};
// Gradient: {c:[[t,'#hex']…], a:[[t,alpha]…]} (at most 8 stops each).
export function gradient(g){return {mode:g.fixed?'fixed':'blend',colorStops:(g.c??[[0,'#ffffff'],[1,'#ffffff']]).map(([position,c])=>({position,color:rgb(c)})),alphaStops:(g.a??[[0,1],[1,1]]).map(([position,alpha])=>({position,alpha}))};}

/**
 * One emitter from a compact spec. Fields (all optional except texture):
 *  id, name, texture ('glow' → textures/glow.png), tiles [cols,rows] + frames {fps|overLife, random}
 *  blend 'additive'|'alpha', order, sort, max, duration, loop, delay (timeline start, s)
 *  rate, bursts [[time,count,cycles?,interval?]], shape {type,radius,angle,arc,thickness,length,box,emitFrom,arcMode},
 *  at [x,y,z], rot [deg x,y,z], spherical, randomDir, jitter, local
 *  life, speed, velocity {min,max} (vector mode), size, sizeXY [x,y], rotation (rad), spin (rad/s)
 *  color '#hex' | ['#a','#b'], alpha, intensity, colorOverLife {c,a}, sizeOverLife, sizeOverLifeY
 *  gravity, drag, align 'velocity'|'spawn'|'vector' (+ alignVector), noise {strength,frequency,speed,octaves,mode}
 *  orbit [x,y,z] rad/s, radial, linear [x,y,z], force [x,y,z], limit {speed, dampen}
 *  collide {y, bounce, dampen}, trail {life, width, widthOverTrail, colorOverTrail, texture}
 *  patch: deep partial merged last, for anything else in the NixieFX schema.
 */
export function emitter(spec,index,T){
 const e=structuredClone(T.emitters[0]),S=(p,v)=>set(e,p,scalar(get(T.emitters[0],p),v));
 e.id=spec.id??`emitter-${index+1}`;e.name=spec.name??e.id;
 e.maxParticles=spec.max??64;e.duration=spec.duration??.5;e.loop=spec.loop??false;e.timeline.start=spec.delay??0;
 const sp=e.spawn,sh=spec.shape??{type:'point'};
 S('spawn.rateValue',spec.rate??0);sp.rate=typeof spec.rate==='number'?spec.rate:0;
 sp.bursts=(spec.bursts??[]).map(([time,count,cycles=1,interval=0,probability=1])=>({time,count,cycles,interval,probability}));
 sp.shape=sh.type;S('spawn.radiusValue',sh.radius??0);sp.radius=typeof sh.radius==='number'?sh.radius:0;
 if(sh.angle!==undefined)sp.angle=sh.angle;if(sh.arc!==undefined)sp.arc=sh.arc;if(sh.arcMode)sp.arcMode=sh.arcMode;if(sh.arcSpread!==undefined)sp.arcSpread=sh.arcSpread;if(sh.thickness!==undefined)sp.radiusThickness=sh.thickness;
 if(sh.length!==undefined)sp.length=sh.length;if(sh.box)sp.box=sh.box;if(sh.emitFrom)sp.emitFrom=sh.emitFrom;
 if(spec.at)sp.position=spec.at;if(spec.rot)sp.rotation=spec.rot;if(spec.local)sp.simulationSpace='local';
 sp.sphericalDirectionAmount=spec.spherical??0;sp.randomDirectionAmount=spec.randomDir??0;sp.randomPositionAmount=spec.jitter??0;
 const init=e.initializeParticle;
 S('initializeParticle.lifetime',spec.life??.5);
 if(spec.sizeXY){init.startSizeSeparateAxes=true;S('initializeParticle.size3D.x',spec.sizeXY[0]);S('initializeParticle.size3D.y',spec.sizeXY[1]);S('initializeParticle.size',spec.sizeXY[0]);}
 else S('initializeParticle.size',spec.size??.3);
 if(spec.rotation!==undefined)S('initializeParticle.rotation',spec.rotation);
 if(spec.spin!==undefined){e.modules.rotation=true;S('initializeParticle.angularVelocity',spec.spin);}
 if(spec.velocity){init.velocity.mode='vector';init.velocity.min=spec.velocity.min;init.velocity.max=spec.velocity.max;}
 else S('initializeParticle.velocity.speed',spec.speed??0);
 const col=spec.color??'#ffffff';
 if(Array.isArray(col)){init.color.mode='random';init.color.color=[...rgb(col[0]),1];init.color.colorB=[...rgb(col[1]),1];}else{init.color.mode='constant';init.color.color=[...rgb(col),1];init.color.colorB=[...rgb(col),1];}
 // Alpha-blended particles never go over 1: NixieFX maps overbright colour through an SDR curve that greys them.
 const alphaBlend=(spec.blend??'additive')!=='additive',intensity=spec.intensity??1;
 S('initializeParticle.color.alpha',spec.alpha??1);S('initializeParticle.color.intensity',alphaBlend&&typeof intensity==='number'?Math.min(1,intensity):intensity);
 if(spec.colorOverLife){e.modules.color=true;e.color.gradient=gradient(spec.colorOverLife);}
 if(spec.sizeOverLife!==undefined){e.modules.size=true;S('billboard.sizeValue',spec.sizeOverLife);
  if(spec.sizeOverLifeY!==undefined){e.billboard.separateAxes=true;S('billboard.sizeValueY',spec.sizeOverLifeY);}else S('billboard.sizeValueY',spec.sizeOverLife);}
 if(spec.gravity!==undefined||spec.drag!==undefined){e.modules.velocity=true;S('forces.gravityValue',spec.gravity??0);S('forces.dragValue',spec.drag??0);e.forces.gravity=typeof spec.gravity==='number'?spec.gravity:0;e.forces.drag=typeof spec.drag==='number'?spec.drag:0;}
 const adv=e.advanced;
 if(spec.orbit||spec.radial!==undefined||spec.linear||spec.speedOverLife!==undefined){e.modules.velocityOverLifetime=true;const v=adv.velocityOverLifetime,base=T.emitters[0].advanced.velocityOverLifetime;
  ['x','y','z'].forEach((k,i)=>{if(spec.orbit)v.orbital[k]=scalar(base.orbital[k],spec.orbit[i]);if(spec.linear)v.linear[k]=scalar(base.linear[k],spec.linear[i]);});
  if(spec.radial!==undefined)v.radial=scalar(base.radial,spec.radial);if(spec.speedOverLife!==undefined)v.speedModifier=scalar(base.speedModifier,spec.speedOverLife);v.space=spec.vSpace??'local';}
 if(spec.force){e.modules.forceOverLifetime=true;adv.forceOverLifetime.force=spec.force;if(spec.forceRandom)adv.forceOverLifetime.randomized=spec.forceRandom;}
 if(spec.noise){e.modules.noise=true;const n=adv.noise;n.mode=spec.noise.mode??'curl';n.strength=scalar(T.emitters[0].advanced.noise.strength,spec.noise.strength??1);n.frequency=spec.noise.frequency??1.5;n.speed=spec.noise.speed??1;n.octaves=spec.noise.octaves??2;if(spec.noise.damping!==undefined)n.damping=spec.noise.damping;}
 if(spec.collide){e.modules.collision=true;Object.assign(adv.collision,{mode:'plane',planeY:spec.collide.y??0,bounce:spec.collide.bounce??.35,dampen:spec.collide.dampen??.45});}
 if(spec.limit){e.modules.limitVelocityOverLifetime=true;adv.limitVelocityOverLifetime.speed=scalar(T.emitters[0].advanced.limitVelocityOverLifetime.speed,spec.limit.speed);adv.limitVelocityOverLifetime.dampen=spec.limit.dampen??.5;}
 if(spec.trail){e.modules.trails=true;const t=adv.trails,base=T.emitters[0].advanced.trails;t.lifetime=scalar(base.lifetime,spec.trail.life??.3);t.width=scalar(base.width,spec.trail.width??.1);
  t.widthOverTrail=scalar(base.widthOverTrail,spec.trail.widthOverTrail??{curve:[[0,1],[1,0]]});t.inheritColor=spec.trail.inheritColor??!spec.trail.colorOverTrail;
  if(spec.trail.colorOverTrail)t.colorOverTrail=gradient(spec.trail.colorOverTrail);if(spec.trail.colorOverLife)t.colorOverLifetime=gradient(spec.trail.colorOverLife);
  t.texture=spec.trail.texture?`textures/${spec.trail.texture}.png`:null;t.minVertexDistance=spec.trail.minVertexDistance??.03;t.worldSpace=spec.trail.worldSpace??true;
  if(spec.trail.material)t.material=materialInstance(spec.trail.material,`${e.id}-trail`,spec.trail.texture??spec.texture);}
 if(spec.tiles&&(spec.tiles[0]>1||spec.tiles[1]>1)){e.modules.textureSheetAnimation=true;const a=adv.textureSheetAnimation;a.tiles=spec.tiles;a.startFrame=0;a.endFrame=spec.tiles[0]*spec.tiles[1]-1;
  a.frameOverTime=scalar(T.emitters[0].advanced.textureSheetAnimation.frameOverTime,spec.frames?.still?0:{curve:[[0,0],[1,1]]});a.cycles=spec.frames?.cycles??1;a.randomStartFrame=spec.frames?.random??false;}
 const r=e.render;r.blend=spec.blend??'additive';r.depthInk=false;r.depthTest=false;r.orderInLayer=spec.order??0;r.sortMode=spec.sort??'none';r.texture=`textures/${spec.texture}.png`;
 if(spec.material)r.material=materialInstance(spec.material,e.id,spec.texture);
 if(spec.align==='velocity'||spec.align==='spawn'){const m=spec.align==='velocity'?'velocity':'spawnDirection';r.alignment=m;r.alignAxis=m;}
 // 'vector' pins the texture top to a fixed direction of the effect frame (default +X, the aim): ground decals.
 if(spec.align==='vector'){r.alignment='vector';r.alignAxis='vector';r.alignmentVector=spec.alignVector??[1,0,0];}
 if(spec.patch)merge(e,spec.patch);
 return e;
}
export const makeEmitter=emitter;

export function materialInstance(mat,emitterId,textureName){
 const m=typeof mat==='string'?{shaderId:mat}:mat;
 const shaderId=m.shaderId??m.id;
 const texPath=textureName?`textures/${textureName}.png`:'';
 const ov=m.overrides??m.paramOverrides??m.params??{};
 return {
  id:m.id??`${emitterId}-${shaderId}`,
  shaderId,
  overrides:ov,
  paramOverrides:ov,
  mainTex:m.mainTex!==undefined?m.mainTex:(texPath?{type:'texture',id:textureName,path:texPath}:null),
 };
}

